			Logging.SaveLog(_tag, ex2);
			return (null, ex2.Message);
		}
	}

	public async Task<(List<string>, string?)> GetCertChainPemAsync(string target, string serverName, int timeout = 4, bool allowInsecure = false)
	{
		List<string> pemList = new List<string>();
		try
		{
			var (host, _, num, _) = Utils.ParseUrl(target);
			using CancellationTokenSource cts = new CancellationTokenSource();
			cts.CancelAfter(TimeSpan.FromSeconds(timeout));
			using TcpClient client = new TcpClient();
			await client.ConnectAsync(host, (num > 0) ? num : 443, cts.Token);
			RemoteCertificateValidationCallback remoteCertificateValidationCallback = (object sender, X509Certificate? certificate2, X509Chain? chain, SslPolicyErrors sslPolicyErrors) => ValidateServerCertificate(sender, certificate2, chain, sslPolicyErrors, allowInsecure);
			(List<string> pemList, string?) result;
			await using (SslStream ssl = new SslStream(client.GetStream(), leaveInnerStreamOpen: false, remoteCertificateValidationCallback))
			{
				SslClientAuthenticationOptions sslClientAuthenticationOptions = new SslClientAuthenticationOptions
				{
					TargetHost = serverName,
					RemoteCertificateValidationCallback = remoteCertificateValidationCallback
				};
				await ssl.AuthenticateAsClientAsync(sslClientAuthenticationOptions, cts.Token);
				if (!(ssl.RemoteCertificate is X509Certificate2 certificate))
				{
					result = (pemList: pemList, null);
				}
				else
				{
					X509Chain x509Chain = new X509Chain();
					x509Chain.Build(certificate);
					pemList.AddRange(x509Chain.ChainElements.Select((X509ChainElement element) => ExportCertToPem(element.Certificate)));
					result = (pemList: pemList, null);
				}
			}
			return result;
		}
		catch (OperationCanceledException)
		{
			Logging.SaveLog(_tag, new TimeoutException($"Connection timeout after {timeout} seconds"));
			return (pemList, $"Connection timeout after {timeout} seconds");
		}
		catch (Exception ex2)
		{
			Logging.SaveLog(_tag, ex2);
			return (pemList, ex2.Message);
		}
	}

	private bool ValidateServerCertificate(object _, X509Certificate? certificate, X509Chain? chain, SslPolicyErrors sslPolicyErrors, bool allowInsecure)
	{
		if (certificate == null)
		{
			return false;
		}
		if (allowInsecure)
		{
			return true;
		}
		if (sslPolicyErrors.HasFlag(SslPolicyErrors.RemoteCertificateNameMismatch))
		{
			return false;
		}
		X509Certificate2 certificate2 = (certificate as X509Certificate2) ?? new X509Certificate2(certificate);
		X509Chain x509Chain = chain ?? new X509Chain();
		x509Chain.ChainPolicy.RevocationMode = X509RevocationMode.Online;
		x509Chain.ChainPolicy.RevocationFlag = X509RevocationFlag.ExcludeRoot;
		x509Chain.ChainPolicy.VerificationFlags = X509VerificationFlags.NoFlag;
		x509Chain.ChainPolicy.VerificationTime = DateTime.Now;
		x509Chain.Build(certificate2);
		if (x509Chain.ChainElements.Count == 0)
		{
			return false;
		}
		string certHashString = x509Chain.ChainElements[checked(x509Chain.ChainElements.Count - 1)].Certificate.GetCertHashString(HashAlgorithmName.SHA256);
		return TrustedCaThumbprints.Contains(certHashString);
	}

	public static string ExportCertToPem(X509Certificate2 cert)
	{
		string text = Convert.ToBase64String(cert.Export(X509ContentType.Cert));
		return "-----BEGIN CERTIFICATE-----\n" + text + "\n-----END CERTIFICATE-----\n";
	}

	public static List<string> ParsePemChain(string pemChain)
	{
		List<string> list = new List<string>();
		if (string.IsNullOrWhiteSpace(pemChain))
		{
			return list;
		}
		pemChain = pemChain.Replace("\r\n", "\n").Replace("\r", "\n");
		int num = 0;
		checked
		{
			while (num < pemChain.Length)
			{
				int num2 = pemChain.IndexOf("-----BEGIN CERTIFICATE-----", num, StringComparison.Ordinal);
				if (num2 == -1)
				{
					break;
				}
				int num3 = pemChain.IndexOf("-----END CERTIFICATE-----", num2, StringComparison.Ordinal);
				if (num3 == -1)
				{
					break;
				}
				int num4 = num2 + "-----BEGIN CERTIFICATE-----".Length;
				string source = pemChain.Substring(num4, num3 - num4);
				source = new string(source.Where((char c) => !char.IsWhiteSpace(c)).ToArray());
				string item = $"{"-----BEGIN CERTIFICATE-----"}\n{source}\n{"-----END CERTIFICATE-----"}\n";
				list.Add(item);
				num = num3 + "-----END CERTIFICATE-----".Length;
			}
			return list;
		}
	}

	public static string ConcatenatePemChain(IEnumerable<string> pemList)
	{
		if (pemList == null)
		{
			return string.Empty;
		}
		return string.Concat(pemList);
	}

	public static string GetCertSha256Thumbprint(string pemCert, bool includeColon = false)
	{
		try
		{
			string certHashString = X509Certificate2.CreateFromPem(pemCert.AsSpan()).GetCertHashString(HashAlgorithmName.SHA256);
			if (includeColon)
			{
				return string.Join(":", from c in certHashString.Chunk(2)
					select new string(c));
			}
			return certHashString;
		}
		catch
		{
			return string.Empty;
		}
	}
